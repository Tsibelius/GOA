//                                 დავალება 7-ე

// მომხმარებელს შემოატანინეთ ტექსტი და გაიგეთ ეს ტექსტი არის თუ არა პალინდრომე (for loop-ის გამოყენებით).

let word = prompt("შეიყვანეთ ტექსტი:");
let reversed = "";
for (let i = word.length - 1; i >= 0; i--) {
  reversed += word[i];
}
if (word === reversed) {
  console.log("ეს ტექსტი პალინდრომია");
} else {
  console.log("ეს ტექსტი არ არის პალინდრომი");
}



