// შექმენით ფუნქცია რომელიც
// დააბრუნებს "გამარჯობა {თქვენი სახელი}"-ს და 
// კონსოლში გამოიტანეთ შედეგი.

function greeting(name) {
  return "მოგესალმებით ბატონო " + name;
}

let result = greeting("გიორგი");
console.log(result);

