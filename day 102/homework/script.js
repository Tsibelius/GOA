// დავალება მე-3

// =====================================================


// შექმენით სია სადაც იქნება სხვადასხვა ტიპის მონაცემები.
// და ახალ სიაში დააბრუნეთ მხოლოდ ის ელემენტები
// რომლებიც იქნება სტრინგ ტიპის მონაცემი (for of-ით)

let mixedArray = [10, "Hello", true, "World", 50, "JavaScript"];
let stringsOnly = [];

for (let item of mixedArray) {
  if (typeof item === "string") {
    stringsOnly.push(item);
  }
}

console.log(stringsOnly);


