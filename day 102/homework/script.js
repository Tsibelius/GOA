// დავალება მე-5

// =====================================================


// შექმენით ობიექტი სადაც შეინახავთ ნებისმიერი ტიპის ინფორმაციას.
// მომხმარებელს შემოატანინეთ key.
// თუ ეს key არის ობიექტში მაშინ კონსოლში გამოაჩინეთ შესაბამისი მნიშვნელობა.
// სხვა შემთხვევაში შემოატანინე value და ობიექტში დაამატეთ.

let info = {
  name: "გიორგი",
  age: 18,
};

let userKey = prompt("შეიყვანეთ ელემენტის სახელი:");

if (userKey in info) {
  console.log(info[userKey]);
} else {
  let userValue = prompt("ასეთი ელემენტის სახელი ვერ მოიძებნა, შეიყვანეთ ელემენტი :");
  info[userKey] = userValue;
  console.log(info);
}


