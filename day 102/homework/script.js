// მომხმარებელს შემოატანინეთ სახელი და ამ სახელის
// თითოეული ასო გამოიტანეთ ცალცალკე for of-ის გამოყენებით

let name = prompt("შეიყვანეთ თქვენი სახელი:");

for (let letter of name) {
  console.log(letter);
}


