// ზოგიერთი ელემენტი უნდა მეორდებოდეს.
// შემდეგ შექმენით ობიექტი სადაც ჩაამატებთ ამ ელემენტს როგორც key
// და მისი მნიშვნელობა იყოს რამდენჯერაც გვხვდება სიაში.

let items = ["apple", "banana", "apple", "xawapuri", "banana", "apple"];
