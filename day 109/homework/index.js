// ==========================================
//                დავალება მე-4
// პირობა: შექმენით სია სადაც იქნება სხვადასხვა ტიპის მონაცემები. 
// თუ ელემენტი number ტიპის მონაცემია მაშინ აიყვანეთ კვადრატში. 
// თუ სტრინგია მაშინ შეაბრუნეთ და ისე დააბრუნეთ. 
// სხვა შემთხვევაში როგორც არის ისე დააბრუნეთ.
// ==========================================

var sawyisiSia = [4, "Hello", true, 7, "World"];
var sabolooSia = [];

for (var i = 0; i < sawyisiSia.length; i++) {
    var elementi = sawyisiSia[i];

    if (typeof elementi == "number") {
        sabolooSia.push(elementi * elementi);
    } else if (typeof elementi == "string") {
        
        var asoebi = [];
        for (var j = elementi.length - 1; j >= 0; j--) {
            asoebi.push(elementi[j]);
        }
        
        sabolooSia.push(asoebi.join(""));
    } else {
        sabolooSia.push(elementi);
    }
}

console.log("დამუშავებული სია: ", sabolooSia);


