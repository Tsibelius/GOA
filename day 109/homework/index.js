var randomRicxvi = Math.floor(Math.random() * 20) + 1;
var momxmareblisRicxvi;


while (momxmareblisRicxvi != randomRicxvi) {
    momxmareblisRicxvi = Number(prompt("გამოიცანით რიცხვი 1-დან 20-მდე:"));
    
    if (momxmareblisRicxvi < randomRicxvi) {
        console.log("უფრო დიდი რიცხვი სცადეთ!");
    } else if (momxmareblisRicxvi > randomRicxvi) {
        console.log("უფრო პატარა რიცხვი სცადეთ!");
    } else {
        console.log("გილოცავთ! თქვენ გამოიცანით: " + randomRicxvi);
    }
}



