// პირობა: შექმენი ობიექტი ავტომობილების შესახებ --> brand , model , year , color
// შენი დავალებაა რომ შებამისი მეთოდის დახმარებით მიიღო სია სადაც იქნბება კიდევ სიები
// key , value წყვილებით , შენი დავალებაა კონსოლში გამოიტანო key ები ცალკე value ბი ცალკე(გამოიყენე for ან forEach)
// ==========================================
console.log("-----__&__-----");
console.log("დავალება 1-ლი :");
var car = {
  brand: "Chevrolet",
  model: "Impala",
  year: 1967,
  color: "Black",
};

var carEntries = Object.entries(car);

carEntries.forEach(([key, value]) => {
  console.log("Key:" + key, " Value:" + value);
});

