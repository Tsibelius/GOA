var book = {
  name: "ვეფხისტყაოსანი",
};

book.author = "შოთა რუსთაველი";
book.year = 1712;
book.amount = 50;

console.log("-----__&__-----");
console.log("დავალება მე-3");
console.log("არის თუ არა სახელი ობიექტსა შინა? :", "name" in book);
console.log("არის თუ არა ფერი ობიექტში? :", "color" in book);

