//                 დავალება მე-2
// პირობა: შექმენი ობიექტი შენს შესახხებ --> name , surname , age
// შექმენი მეორე ობიექტი სადაც იქნება --> adress , hobby , favColor
// შენი დავალებაა გააერთიანო ეს ორივე ობიექტი ერთ ობიექტში და შეინახო ცვლადში
// შემდეგ მოახდინე ამ ობიექტის დესტრუქცია და გამოიტანე კონსოლში თითოეული მათგანი
// ==========================================

let personalInfo = {
  name: "მეფე ვახტანგ",
  surname: "გორგასალი",
  age: 15,
};

let extraInfo = {
  adress: "ტბილისი",
  hobby: "ზრუნვაჲ იბერიისაჲ",
  favColor: "მეწამული სისხლისფერი",
};

let mergedObj = { ...personalInfo, ...extraInfo };

let { name, surname, age, adress, hobby, favColor } = mergedObj;
console.log("-----__&__-----");
console.log("დავალება მე-2 :");
console.log("სახელი:", name);
console.log("გვარი:", surname);
console.log("ასაკი:", age);
console.log("მისამართი:", adress);
console.log("მოწოდებაჲ:", hobby);
console.log("საყვარელი ფერი:", favColor);

