// -----------------------------------------------------------------
// შექმენით მინიმუმ 5 ელემენტიანი სია, რიცხვებიც იყოს და სტრინგებიც.
// ამ სიას გადაუარეთ და ყველა რიცხვი გადაამრავლეთ ერთმანეთზე.
// -----------------------------------------------------------------

let mixed = [5, "hello", 3, "ხაჭაპური", 2, 10];
let producti = 1;

for (let i = 0; i < mixed.length; i++) {
  let check = mixed[i] * 1; 

  if (check == mixed[i]) {  
    producti *= mixed[i];
  }
}

console.log("სიაში ნაპოვნი რიცხვების ნამრავლია :", producti);