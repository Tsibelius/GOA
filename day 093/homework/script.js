//                                               1-ლი დავალება


// -----------------------------------------------------------------------------------------------
// მოცემული გაქვთ სია:  [100, 50, 0, -300, 150, 20, 40, 900] და გამოიტანეთ ყველაზე პატარა რიცხვი.
// (მთლიანი სია შეამოწმეთ და ისე, ხელით არ ამოარჩიოთ).
//------------------------------------------------------------------------------------------------

let numbers = [100, 50, 0, -300, 150, 20, 40, 900];

let smallest = numbers[0];

for (let i = 1; i < numbers.length; i++) {
  if (numbers[i] < smallest) {
    smallest = numbers[i];
  }
}

console.log("დავალება 1-ლი : ყველაზე პატარა რიცხვია :", smallest);




//                                               მე-2 დავალება


// --------------------------------------------------------------
// მოცემული გაქვთ სია: ['01001011100', '100111110', '110101010'].
// ამ სიის თითოეული ელემენტი არის ორობით სისტემაში.
// გადაიყვანეთ ათობითში და ჩაამატეთ ახალ სიაში. 
// --------------------------------------------------------------

let binaries = ['01001011100', '100111110', '110101010'];
let decimals = [];

for (let i = 0; i < binaries.length; i++) {
  let bina = binaries[i];
  let decimal = 0;
  let power = 0;

  for (let j = bina.length - 1; j >= 0; j--) {
    let bi = bina[j] * 1; 
    decimal += bi * (2 ** power);
    power++;
  }

  decimals.push(decimal);
}

console.log("დავალება მე-2 : ათობითი რიცხვებია :", decimals);




//                                               მე-3 დავალება


// ---------------------------------------------------------------------------------
// მომხმარებელს შემოატანინეთ რიცხვი. და ამ რიცხვის გამყოფები გამოიტანეთ სიის სახით.
// ---------------------------------------------------------------------------------

let num = Number(prompt("შეიყვანეთ რიცხვი:"));
let miau = [];

for (let i = 1; i <= num; i++) {
  if (num % i === 0) {
    miau.push(i);
  }
}

console.log("მე-3 დავალება : ამ რიცხვის გამყოფებია :", miau);




//                                               მე-4 დავალება


// -----------------------------------------------------------------------------------------
// შექმენით სია, სადაც ეწერა ამ ჯგუფის მოსწავლეების სახელები.
// დააჯგუფეთ ლუწ ინდექსზე მდგომი სახელები ცალკე და კენტ ინდექსზე მდგომი სახელები ცალკე.
// -----------------------------------------------------------------------------------------

let students = ["გიორგი", "ნიკოლოზი", "აღა მაჰმად ხანი", "ლუკა", "ნიკოლოზი", "ნაპოლეონი"];

let evenIndex = [];
let oddIndex = [];

for (let i = 0; i < students.length; i++) {
  if (i % 2 === 0) {
    evenIndex.push(students[i]);
  } else {
    oddIndex.push(students[i]);
  }
}

console.log("ლუწ ინდექსებზე მდგომი სახელებია :", evenIndex);
console.log("კენტ ინდექსებზე მდგომი სახელებია :", oddIndex);




